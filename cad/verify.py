def needed_deflection(rdeg):
    rp = affinity.rotate(ring2d, rdeg, origin=(0, 0))
    if not bump_region.intersects(rp) or bump_region.intersection(rp).area < 1e-4:
        return 0.0
    lo, hi = 0.0, 3.0
    for _ in range(20):
        mid = (lo + hi) / 2
        sc = (20.7 - mid) / 20.7          # radial shift of the bump tip (r = 20.7)
        b = affinity.scale(bump_region, sc, sc, origin=(0, 0))
        if b.intersection(rp).area > 1e-4:
            lo = mid
        else:
            hi = mid
    return hi


