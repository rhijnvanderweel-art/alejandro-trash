def sweep(moving_fn, fixed: dict, steps, label):
    hits = []
    for t in steps:
        m = moving_fn(t)
        for n, f in fixed.items():
            v = ivol(m, f)
            if v > EPS_VOL:
                hits.append((round(float(t), 2), n, round(v, 2)))
    check(not hits, label + ("" if not hits else f" -> {hits[:4]}"))


