def check(cond, msg):
    tag = "PASS" if cond else "FAIL"
    log(f"- **{tag}** - {msg}")
    if not cond:
        failures.append(msg)


def ivol(a: Manifold, b: Manifold) -> float:
    ba, bb = a.bounding_box(), b.bounding_box()
    if any(ba[i] > bb[i + 3] or bb[i] > ba[i + 3] for i in range(3)):
        return 0.0
    return (a ^ b).volume()


def collisions(parts: dict, only=None, ignore=()):
    """Return list of (a, b, volume) with real overlap."""
    res = []
    names = list(parts)
    for a, b in itertools.combinations(names, 2):
        if only and not (any(o in a for o in only) or any(o in b for o in only)):
            continue
        if (a, b) in ignore or (b, a) in ignore:
            continue
        v = ivol(parts[a], parts[b])
        if v > EPS_VOL:
            res.append((a, b, v))
    return res


def full_assembly(rotor_deg=0.0, alphas=None):
    alphas = alphas or {}
    parts = dict(F.centre_parts(rotor_deg))
    for k in range(F.N):
        parts.update(F.station_parts(k, alphas.get(k, 0.0)))
    return parts


