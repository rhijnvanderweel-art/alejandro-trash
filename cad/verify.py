def plan_free(k, rdeg):
    rp = affinity.rotate(rotor_poly, rdeg, origin=(0, 0))
    bp = affinity.rotate(bolt_plan, k * F.PITCH, origin=(0, 0))
    ang = math.radians(k * F.PITCH)

    def hit(s):
        return bp.intersection(affinity.translate(rp, s * math.cos(ang), s * math.sin(ang))).area > 1e-4
    # moving the bolt inward by s == moving the rotor outward by s
    if not hit(F.E):
        return F.E
    lo, hi = 0.0, F.E
    for _ in range(18):
        mid = (lo + hi) / 2
        if hit(mid):
            hi = mid
        else:
            lo = mid
    return lo


