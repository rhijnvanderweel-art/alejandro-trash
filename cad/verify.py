def max_free_stroke(k, rotor_deg, hi=F.E):
    rot = F.rot_z(F.make_rotor(), rotor_deg)
    lo = 0.0
    if ivol(F.rot_z(F.make_bolt(hi), k * F.PITCH), rot) <= EPS_VOL:
        return hi
    for _ in range(22):
        mid = (lo + hi) / 2
        if ivol(F.rot_z(F.make_bolt(mid), k * F.PITCH), rot) > EPS_VOL:
            hi = mid
        else:
            lo = mid
    return lo


